// Writes Leaflet's and MarkerCluster's CSS into a module the map chunk injects,
// so pages that are not the map never download it. Run after updating either package.
import { readFileSync, writeFileSync } from 'node:fs';

const css = ['leaflet/dist/leaflet.css', 'leaflet.markercluster/dist/MarkerCluster.css']
  .map((file) => readFileSync(new URL(`../node_modules/${file}`, import.meta.url), 'utf8'))
  .join('\n')
  .replace(/\/\*[\s\S]*?\*\//g, '')
  .replace(/\s+/g, ' ')
  .replace(/\s*([{};:,>])\s*/g, '$1')
  .trim();

writeFileSync(
  new URL('../src/forum/map/leafletCss.ts', import.meta.url),
  `// Generated by scripts/leaflet-css.mjs from leaflet 1.9.4 and leaflet.markercluster 1.5.3. Do not edit.\nexport default ${JSON.stringify(css)};\n`
);
