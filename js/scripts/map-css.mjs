// Writes MapLibre's CSS into a module the map chunk injects, so pages that are
// not a map never download it. Run after updating maplibre-gl.
import { readFileSync, writeFileSync } from 'node:fs';

const css = readFileSync(new URL('../node_modules/maplibre-gl/dist/maplibre-gl.css', import.meta.url), 'utf8')
  .replace(/\/\*[\s\S]*?\*\//g, '')
  .replace(/\s+/g, ' ')
  .replace(/\s*([{};:,>])\s*/g, '$1')
  .trim();

writeFileSync(
  new URL('../src/forum/map/mapCss.ts', import.meta.url),
  `// Generated by scripts/map-css.mjs from maplibre-gl ${JSON.parse(readFileSync(new URL('../node_modules/maplibre-gl/package.json', import.meta.url))).version}. Do not edit.\nexport default ${JSON.stringify(css)};\n`
);
